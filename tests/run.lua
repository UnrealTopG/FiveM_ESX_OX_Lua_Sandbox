local here = debug.getinfo(1,'S').source:sub(2):match('^(.*[/\\])') or './'
local S = dofile(here .. '../init.lua')
local passed, failed = 0, 0
local function eq(expected,actual)
    if expected~=actual then error(('expected %s but got %s'):format(tostring(expected),tostring(actual)),2) end
end
local function check(name, fn)
    S.reset()
    local ok, err = xpcall(fn, debug.traceback)
    if ok then passed=passed+1; print('[PASS] '..name)
    else failed=failed+1; io.stderr:write('[FAIL] '..name..'\n'..tostring(err)..'\n') end
end
check('ESX shared object and player defaults',function()
    local esx=exports['es_extended']:getSharedObject()
    eq(ESX,esx)
    local p=S.createPlayer(7,{name='Tester',identifier='license:tester'})
    eq(p,ESX.GetPlayerFromId(7))
    eq(p,ESX.GetPlayerFromIdentifier('license:tester'))
    eq('Tester',GetPlayerName(7))
    eq(500,p.getMoney())
    eq(5000,p.getAccount('bank').money)
    eq(500,exports.ox_inventory:GetItemCount(7,'money'))
    eq('unemployed',p.getJob().name)
end)
check('ESX bank and inventory cash remain in sync',function()
    local p=S.createPlayer(1)
    eq(true,p.addAccountMoney('bank',150))
    eq(5150,p.getAccount('bank').money)
    eq(false,p.removeAccountMoney('bank',7000))
    eq(true,p.addMoney(100))
    eq(600,p.getMoney())
    eq(true,exports.ox_inventory:RemoveItem(1,'money',70))
    eq(530,p.getAccount('money').money)
    eq(false,p.removeMoney(1000))
    eq(true,exports.ox_inventory:AddItem(1,'black_money',80))
    eq(80,p.getAccount('black_money').money)
end)
check('Jobs grades, groups and metadata',function()
    local p=S.createPlayer(1)
    eq(true,p.setJob('police',2))
    eq('sergeant',p.getJob().grade_name)
    eq(false,p.setJob('invalid',1))
    eq(1,#ESX.GetExtendedPlayers('job','police'))
    p.setGroup('admin'); eq('admin',p.getGroup())
    p.setMeta('stress',15); eq(15,p.getMeta('stress'))
    S.setSide('client',1)
    eq('police',ESX.GetPlayerData().job.name)
    eq('admin',ESX.PlayerData.group)
end)
check('Inventory stacking, slots, metadata and search',function()
    S.createPlayer(1)
    local inv=exports.ox_inventory
    eq(true,inv:AddItem(1,'water',2,{type='cold'}))
    eq(true,inv:AddItem(1,'water',3,{type='hot'}))
    eq(true,inv:AddItem(1,'water',4,{type='cold'}))
    eq(9,inv:Search(1,'count','water'))
    eq(6,inv:Search(1,'count','water',{type='cold'}))
    eq(2,#inv:Search(1,'slots','water'))
    eq(true,inv:RemoveItem(1,'water',5))
    eq(4,inv:GetItemCount(1,'water'))
    local slot=inv:GetSlotIdWithItem(1,'water',{type='hot'})
    eq(true,inv:SetMetadata(1,slot,{type='warm',durability=90}))
    eq(90,inv:GetSlot(1,slot).metadata.durability)
    S.setSide('client',1)
    eq(4,inv:Search('count','water'))
end)
check('Inventory capacity, invalid counts and weight',function()
    S.createPlayer(1,{slots=2,maxWeight=600,accounts={money=0}})
    local inv=exports.ox_inventory
    eq(true,inv:AddItem(1,'water',1))
    eq(false,inv:CanCarryItem(1,'bread',1))
    eq(false,inv:AddItem(1,'bread',1))
    eq(false,inv:AddItem(1,'water',-1))
    eq(false,inv:RemoveItem(1,'water',2))
    eq(1,inv:GetItemCount(1,'water'))
    eq(true,inv:ClearInventory(1))
    eq(0,inv:GetItemCount(1,'water'))
end)
check('Inventory removal does not partially mutate',function()
    S.createPlayer(1,{accounts={money=0}})
    S.inventory.AddItem(1,'water',2,{kind='a'})
    S.inventory.AddItem(1,'water',3,{kind='b'})
    eq(false,S.inventory.RemoveItem(1,'water',4,{kind='a'}))
    eq(5,S.inventory.GetItemCount(1,'water'))
    eq(false,S.inventory.AddItem(1,'water',4,nil,1)) -- occupied with mismatched metadata
end)
check('Stashes are independent',function()
    S.createPlayer(1)
    local inv=exports.ox_inventory
    eq(true,inv:RegisterStash('police_locker','Police Locker',3,3000))
    eq(true,inv:AddItem('police_locker','bandage',2))
    eq(2,inv:GetItemCount('police_locker','bandage'))
    eq(0,inv:GetItemCount(1,'bandage'))
end)
check('ESX callbacks and usable items',function()
    S.createPlayer(10)
    ESX.RegisterServerCallback('my:money',function(src,cb,factor)
        cb(ESX.GetPlayerFromId(src).getMoney()*factor)
    end)
    S.setSide('client',10)
    eq(1000,ESX.AwaitServerCallback('my:money',2))
    local result
    ESX.TriggerServerCallback('my:money',function(value) result=value end,3)
    eq(1500,result)
    S.setSide('server')
    ESX.RegisterUsableItem('water',function(src) ESX.GetPlayerFromId(src).removeInventoryItem('water',1) end)
    eq(true,exports.ox_inventory:AddItem(10,'water',2))
    eq(true,S.useItem(10,'water'))
    eq(1,exports.ox_inventory:GetItemCount(10,'water'))
end)
check('ox_lib server/client callbacks',function()
    S.createPlayer(3)
    S.setSide('server')
    lib.callback.register('getName',function(src,prefix) return prefix..ESX.GetPlayerFromId(src).name end)
    S.setSide('client',3)
    eq('Hi Mock Player 3',lib.callback.await('getName',false,'Hi '))
    local got
    lib.callback('getName',false,function(text) got=text end,'Hello ')
    eq('Hello Mock Player 3',got)
    lib.callback.register('clientStatus',function() return 'online' end)
    S.setSide('server')
    eq('online',lib.callback.await('clientStatus',3))
end)
check('events track sender and correct side',function()
    S.createPlayer(4)
    local serverSource, clientPayload
    S.setSide('server')
    RegisterNetEvent('shop:buy',function(item) serverSource=source; eq('bread',item) end)
    S.setSide('client',4)
    RegisterNetEvent('shop:result',function(ok) clientPayload=ok end)
    TriggerServerEvent('shop:buy','bread')
    eq(4,serverSource)
    S.setSide('server')
    TriggerClientEvent('shop:result',4,true)
    eq(true,clientPayload)
    eq(2,#S.getEvents())
    eq('server',S.getEvents('shop:buy')[1].type)
end)
check('scheduler is deterministic and nonblocking',function()
    local result={}
    CreateThread(function()
        result[#result+1]='first'
        Wait(10)
        result[#result+1]='second'
    end)
    SetTimeout(5,function() result[#result+1]='timer' end)
    S.advance(0)
    eq('first',result[1])
    S.advance(5)
    eq('timer',result[2])
    S.advance(5)
    eq('second',result[3])
    eq(10,GetGameTimer())
end)
