end)
check('oxmysql SQL result mocks and query tracking',function()
    S.setSQL('SELECT * FROM users WHERE id = ?',{{id=1,name='Test'}})
    local rows=MySQL.query.await('SELECT * FROM users WHERE id = ?',{1})
    eq('Test',rows[1].name)
    eq(1,#S.state.dbCalls)
    S.setSQL('UPDATE users SET name = ?',3)
    eq(3,MySQL.update.await('UPDATE users SET name = ?',{'Tester'}))
end)
check('reset prevents cross-test state leaks',function()
    S.createPlayer(1)
    S.inventory.AddItem(1,'water',1)
    S.reset()
    eq(nil,ESX.GetPlayerFromId(1))
    eq(0,#S.getEvents())
    eq(0,#ESX.GetPlayers())
    eq(0,#S.state.dbCalls)
end)
print(('\nTest result: %d passed, %d failed'):format(passed,failed))
if failed>0 then os.exit(1) end
